CREATE TABLE restaurant_candidates (
    room_id UUID NOT NULL,
    restaurant_id VARCHAR(32) NOT NULL,
    position SMALLINT NOT NULL,
    name TEXT NOT NULL,
    photo_url TEXT,
    opening_hours TEXT,
    closed_days TEXT,
    dinner_budget TEXT,
    access TEXT,
    station_name TEXT,
    detail_url TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    source TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (room_id, restaurant_id),
    CONSTRAINT restaurant_candidates_room_fk FOREIGN KEY (room_id) REFERENCES rooms (id) ON DELETE CASCADE,
    CONSTRAINT restaurant_candidates_position_unique UNIQUE (room_id, position),
    CONSTRAINT restaurant_candidates_position_valid CHECK (position BETWEEN 1 AND 5),
    CONSTRAINT restaurant_candidates_name_not_blank CHECK (char_length(btrim(name)) > 0),
    CONSTRAINT restaurant_candidates_source_valid CHECK (source = 'hotpepper'),
    CONSTRAINT restaurant_candidates_coordinates_pair CHECK ((latitude IS NULL) = (longitude IS NULL)),
    CONSTRAINT restaurant_candidates_latitude_valid CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT restaurant_candidates_longitude_valid CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);
